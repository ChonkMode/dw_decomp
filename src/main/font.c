uint8_t COLORCODE_LOWBITS = 0x01;
uint8_t COLORCODE_HIGHBITS = 0x10;

int32_t RENDER_AREA_POINTER;
uint8_t RENDER_AREA[3600];

void initializeFontCLUT(void)
{
	RECT rect;

	clearTextArea();

	setRECT(&rect, 208, 488, 16, 1);
	LoadImage(&rect, FONT_CLUT);

	RENDER_AREA_POINTER = 0;
}

void clearTextArea(void)
{
	RECT rect;

	setRECT(&rect, 0, 0, 256, 256);
	clearTextSubArea(&rect);
}

void clearTextSubArea(RECT *rect)
{
	rect->x = (rect->x / 4) + 704;
	rect->y += 256;
	rect->w >>= 2;
	ClearImage(rect, 0, 0, 0);
}

void setTextColor(int32_t color)
{
	COLORCODE_LOWBITS = color & 0xf;
	COLORCODE_HIGHBITS = COLORCODE_LOWBITS << 4;
}

int32_t drawGlyph(uint16_t codepoint, int32_t x, int32_t y)
{
	RECT rect;
	uint16_t *g;
	uint8_t *out;
	uint16_t bits;
	uint8_t px;
	int32_t n;
	int32_t i;

	if ((uint32_t)x >= 0xf4) {
		return 0;
	}

	if ((uint32_t)y >= 0xf4) {
		return 0;
	}

	codepoint = ((codepoint & 0xff) << 8) + ((codepoint & 0xff00) >> 8);
	CHAR_TO_GLYPH_TABLE[78] = codepoint;

	for (n = 0;; ++n) {
		if (codepoint == CHAR_TO_GLYPH_TABLE[n]) {
			break;
		}
	}

	g = GLYPH_DATA[n].pixelData;
	RENDER_AREA_POINTER = (RENDER_AREA_POINTER + 1) % 0x32;
	out = RENDER_AREA + RENDER_AREA_POINTER * 72;
	for (i = 0; i < 0xb; i++) {
		bits = *g++;

		px = 0;
		if ((bits & 0x8000) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x4000) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;

		px = 0;
		if ((bits & 0x2000) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x1000) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;

		px = 0;
		if ((bits & 0x800) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x400) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;

		px = 0;
		if ((bits & 0x200) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x100) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;

		px = 0;
		if ((bits & 0x80) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x40) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;

		px = 0;
		if ((bits & 0x20) == 0) {
			px |= COLORCODE_LOWBITS;
		}

		if ((bits & 0x10) == 0) {
			px |= COLORCODE_HIGHBITS;
		}

		*out++ = px;
	}

	setRECT(&rect, (x / 4) + 704, y + 256, 3, 11);
	LoadImage(&rect, (u_long *)(RENDER_AREA + RENDER_AREA_POINTER * 72));

	return *g;
}

// clang-format off
void drawString(str, x, y)
	char *str;
	uint16_t x;
	int32_t y;
// clang-format on
{
	uint16_t glyph;
	uint16_t hi;
	uint16_t lo;

	while (*str != 0) {
		if (isAsciiEncoded(str) != 0) {
			if (*str == 0x2e) {
				glyph = 0x8142;
			} else if (*str == 0x27) {
				glyph = 0x8175;
			} else {
				glyph = convertAsciiToJis(*str);
			}

			glyph = swapShortBytes(glyph);
			str++;
		} else {
			lo = *str;
			str++;
			hi = *str;
			lo = (uint8_t)lo;
			hi = (uint8_t)hi;
			lo = lo << 8;
			str++;
			glyph = swapShortBytes(lo | hi);
		}

		x += drawGlyph(glyph, x, y);
	}
}
